"""Запас прочности: превращает оценку в сигнал о цене.

Полоса стоимости сама по себе ответа не даёт. Она лежит рядом с ценой, и
читатель вынужден делить в уме — а деление это не такое простое, как кажется,
потому что «дёшево» у Грэма означает не одно, а три разных условия сразу.

**Гл. 20, «Запас надёжности».** Запас — это не скидка к прошлому пику и не
процент от справедливой цены, придуманный задним числом. Это разница между
тем, что компания зарабатывает, и тем, что можно получить без риска. Грэм
формулирует прямо: акция интересна, когда её доходность заметно выше
доходности качественной облигации, — и вся глава об этом.

Отсюда три источника, и они независимы:

    1. запас по стоимости   (опорная оценка − цена) / опорная оценка
    2. запас по ставке      нормальная прибыль / цена − доходность ОФЗ
    3. прохождение свода    рубильник, а не слагаемое

**Почему пик не годится.** Соблазн считать запас от «цена на треть ниже
максимума» велик, и он неверен: максимум — это чужая ошибка в оценке, а не
мера стоимости. Отсчитывая от него, мы объявляем запасом то, что на деле
является чужим разочарованием. У Грэма запас всегда отсчитывается **от дела**.

**Свод понижает сигнал, а не гасит его.** Гл. 20 стоит после глав 14 и 15, а
не вместо них, и дешёвая плохая компания у Грэма не «выгодна», она плохая. По
этому рассуждению непрохождение свода должно было бы отменять сигнал совсем —
так и было задумано сперва.

На данных приём не выжил. Полный свод защитного инвестора проходят две
компании из тридцати шести, и провал почти у всех остальных вызван одним и тем
же: десятилетний ряд дивидендов оборвался в 2022 году. Это свойство рынка, а
не тридцати четырёх компаний по отдельности, и гасить по нему сигнал значит
переносить общий разрыв в приговор каждой.

Поэтому рубильник оставлен только там, где он и вправду рубильник: оценка
отказана по структуре капитала — сигнала нет, потому что нет и оценки. Провал
свода понижает благоприятный сигнал до приемлемого и едет отдельной строкой,
чтобы читатель видел оба факта сразу: цена хороша, отбор не пройден.

**Дешевизна и ловушка различаются, и различать их обязан расчёт.** Формула
гл. 32 спрашивает «сколько денег вернётся владельцу и под какую ставку это
дисконтировать». Она не спрашивает «а дойдут ли они до него», и потому
структурно изувеченную компанию видит просто дешёвой. Башнефть при P/B 0,20 —
не ошибка рынка: дисконт держится тем, что миноритарий не получает ни
контроля, ни раскрытия, ни предсказуемого дивиденда.

Формулой это не лечится, зато ловится признаками — см. `value_traps`. Они не
отменяют сигнал и не выносят приговора компании: они не дают назвать
благоприятным то, чему для благоприятности не хватает не цены, а доверия.

**Опорная оценка — лестница прибыли при множителе с надбавкой за риск.** Не
середина полосы: весь смысл приёма в том, чтобы ошибаться в свою пользу, а
середина такого свойства не имеет. Но и не низ полосы: низ берётся как
минимум по всем трём лестницам, то есть это худшая ступень при худшем
множителе. У Лукойла низ даёт 2 123 ₽ при цене 5 234 — «запас −146%» не
сообщает ничего, кроме того, что денежная и бухгалтерская лестницы разошлись
вчетверо. Опора же берётся по прибыли, потому что это та величина, которую
оценивает формула гл. 32, и та, с которой сопоставим купон облигации.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

# ── Ступени запаса по стоимости ────────────────────────────────────────────
# Треть — сам Грэм: цена должна быть «существенно ниже» стоимости, и гл. 20
# оперирует именно этим порядком. Ниже трети запас ещё есть, но он уже не
# переживает ошибку в оценке, поэтому ступень названа «приемлемо», а не
# «благоприятно».
MARGIN_FAVOURABLE = 1 / 3
MARGIN_ACCEPTABLE = 0.15

# ── Запас по ставке ────────────────────────────────────────────────────────
# Гл. 14 требует, чтобы отдача акции была не ниже доходности качественной
# облигации. Ноль пунктов — это буквальное прочтение; надбавка ниже добавлена
# потому, что у акции доходность не гарантирована, а у облигации гарантирована,
# и равенство при таком различии означает переплату.
YIELD_SPREAD_COMFORTABLE = 3.0
YIELD_SPREAD_THIN = 0.0

# ── Признаки ловушки стоимости ─────────────────────────────────────────────
# P/B, ниже которого дешевизна перестаёт читаться как скидка. Половина
# балансового капитала — та черта, за которой рынок говорит уже не «я
# ошибся», а «этот капитал до меня не дойдёт». Грэм такие случаи разбирал
# отдельно (гл. 15, NCAV) и с требованием ликвидности активов, а не просто
# «дёшево по балансу».
TRAP_PRICE_TO_BOOK = 0.5

# Дисконт, при котором понижения на ступень уже мало и сигнал упирается в
# потолок. Десятая часть балансовой стоимости — это не «рынок недооценил», это
# рынок отказался от компании, и спорить с ним нормализованной прибылью
# прошлых лет бессмысленно: нормализация смотрит назад, цена смотрит вперёд.
#
# Случай, ради которого поставлено: Евротранс. Нормальная прибыль 34,6 ₽ на
# акцию, балансовая стоимость 214 ₽, цена 21,9 ₽ — оценка по заработку даёт
# 165 ₽ и «запас 83%». Цена при этом упала со 147 ₽ на фоне неплатежей по
# облигациям, и запас тут ровно один: наш расчёт ещё не заметил, что случилось.
TRAP_PRICE_TO_BOOK_SEVERE = 0.25

# Доля удержанной прибыли, осевшая в балансовом капитале, ниже которой деньги
# считаются не дошедшими до владельца. Половина — величина суждения: часть
# удержанного законно уходит в переоценки и курсовые, но половина и больше —
# это уже не шум.
TRAP_RETENTION_SHARE = 0.5

# ── Рычаг: потолок сигнала ─────────────────────────────────────────────────
# Отношение долга к капиталу, выше которого запас прочности не объявляется,
# сколько бы ни было насчитано по заработку.
#
# Причина в самом понятии запаса. Гл. 20 определяет его как разницу между тем,
# что дело зарабатывает, и тем, что можно получить без риска, — но разница эта
# принадлежит владельцу только после кредитора. У Аэрофлота долг больше
# капитала в двенадцать раз: заработок может быть каким угодно, до акционера
# он дойдёт лишь тем, что останется, и «запас 50%», посчитанный по прибыли,
# описывает не его положение, а положение держателя долга.
#
# Порог вдвое мягче грэмовского. Гл. 14 требует долга не выше капитала;
# здесь — не выше двух капиталов, потому что цель не повторить отбор (он и так
# стоит рядом отдельной колонкой), а не дать сигналу соврать.
LEVERAGE_NO_SAFETY = 2.0

# Рычаг, при котором сигнал становится не «без запаса», а предупреждением.
# Вчетверо больше собственного капитала — величина, при которой годовое
# движение прибыли уже не имеет значения: владельцу достаётся то, что осталось
# после кредитора, а осталось может не остаться ничего.
LEVERAGE_DANGEROUS = 4.0

# Натянутое покрытие само по себе к опасности не приравнивается: у компании
# без долга оно и не считается. Но вместе с рычагом выше грэмовского один к
# одному это уже сочетание, при котором проценты съедают заработок, а
# перезанять не на что. Случай Евротранса: покрытие 1,42 при рычаге 1,97.
LEVERAGE_WITH_STRAIN = 1.0

# Покрытие, ниже которого проценты съедают две трети операционной прибыли.
# Это не «тонко» — это положение, из которого один слабый год выводит в убыток.
#
# Граница отделена от `COVERAGE_STRAINED` (2,5×) намеренно. У Белуги покрытие
# 2,02 при рычаге 1,7: запас невелик, и надбавку за это она получает, но
# предупреждением такое называть нельзя — операционная прибыль вдвое больше
# процентов. У Евротранса 1,42, у МТС 1,04, у Эталона 0,49 — вот там оно.
COVERAGE_CRITICAL = 1.5

# ── Состояния сигнала ──────────────────────────────────────────────────────
FAVOURABLE = "favourable"     # запас есть по обоим источникам
ACCEPTABLE = "acceptable"     # запас есть, но тонкий
FAIR = "fair"                 # цена около стоимости
EXPENSIVE = "expensive"       # цена выше стоимости
BOND_BETTER = "bond_better"   # облигация даёт больше без риска
NO_SIGNAL = "no_signal"       # свод не пройден или считать не из чего
# Состояние, которого шкале не хватало. Все прочие говорят о цене — дорого,
# дёшево, вровень; это говорит о самой компании и потому старше всех.
#
# Нужда в нём видна на Аэрофлоте: долг больше капитала в двенадцать раз, и
# лучшее, что умела сказать прежняя шкала, — «около стоимости». Формально
# верно, по существу — приглашение. Консервативного инвестора такая бумага
# должна отталкивать с первого взгляда, а не требовать чтения примечаний.
DANGEROUS = "dangerous"       # баланс способен стереть владельца

LABELS = {
    FAVOURABLE: "благоприятная",
    ACCEPTABLE: "приемлемая",
    FAIR: "около стоимости",
    EXPENSIVE: "выше стоимости",
    BOND_BETTER: "облигация выгоднее",
    DANGEROUS: "опасная",
    NO_SIGNAL: "сигнала нет",
}


@dataclass
class Safety:
    """Запас прочности и сигнал по цене."""

    signal: str = NO_SIGNAL
    reason: Optional[str] = None

    # Запас по стоимости, доля опорной оценки. Отрицательный — цена выше.
    value_margin: Optional[float] = None
    reference: Optional[float] = None  # опорная оценка, от которой считан запас
    price: Optional[float] = None

    # Запас по ставке, процентных пунктов.
    earnings_yield: Optional[float] = None
    risk_free_rate: Optional[float] = None
    yield_spread: Optional[float] = None

    # Рубильник: прошла ли компания свод критериев.
    screen_clears: Optional[bool] = None

    # Проверка против восстановительной стоимости (Гринвальд).
    replacement: Optional[dict] = None

    # Признаки ловушки стоимости: почему дешевизна может быть не скидкой.
    traps: list = field(default_factory=list)

    # Тест гл. 15: чистая стоимость оборотных активов против цены.
    ncav: Optional[dict] = None

    # Долг к собственному капиталу.
    leverage: Optional[float] = None

    notes: list = field(default_factory=list)

    @property
    def label(self) -> str:
        return LABELS[self.signal]

    def as_dict(self) -> dict:
        return {
            "signal": self.signal,
            "label": self.label,
            "reason": self.reason,
            "value_margin": self.value_margin,
            "reference": self.reference,
            "price": self.price,
            "earnings_yield": self.earnings_yield,
            "risk_free_rate": self.risk_free_rate,
            "yield_spread": self.yield_spread,
            "screen_clears": self.screen_clears,
            "replacement": self.replacement,
            "traps": self.traps,
            "ncav": self.ncav,
            "leverage": self.leverage,
            "notes": self.notes,
        }


def replacement_check(
    value_per_share: Optional[float],
    book_value_per_share: Optional[float],
) -> Optional[dict]:
    """Оценка против восстановительной стоимости, Гринвальд.

    Балансовый капитал — грубое приближение к тому, во сколько обошлось бы
    построить это дело заново. Если оценка по способности зарабатывать
    заметно ниже — это не ошибка расчёта, а диагноз: активы не отрабатывают
    стоимость капитала. Построить такой бизнес дороже, чем купить, и значит
    новых конкурентов в отрасли не появится, но и владельцу радости мало.

    Обратный случай — оценка заметно выше восстановительной стоимости —
    означает, что дело защищено чем-то, чего на балансе нет: положением,
    лицензией, привычкой покупателя. Такое преимущество бывает настоящим, но
    доказывать его должен не расчёт, а рассказ о компании.
    """
    if not value_per_share or not book_value_per_share or book_value_per_share <= 0:
        return None

    ratio = value_per_share / book_value_per_share
    if ratio < 0.8:
        verdict = "ниже восстановительной"
        reason = (
            f"оценка по заработку {value_per_share:.0f} ₽ ниже балансовой "
            f"стоимости {book_value_per_share:.0f} ₽ — активы не отрабатывают "
            f"стоимость капитала"
        )
    elif ratio > 1.5:
        verdict = "выше восстановительной"
        reason = (
            f"оценка по заработку {value_per_share:.0f} ₽ выше балансовой "
            f"стоимости {book_value_per_share:.0f} ₽ — разницу держит что-то, "
            f"чего на балансе нет, и это надо уметь назвать"
        )
    else:
        verdict = "вровень"
        reason = None

    return {
        "ratio": round(ratio, 2),
        "verdict": verdict,
        "reason": reason,
        "value_per_share": round(value_per_share, 2),
        "book_value_per_share": round(book_value_per_share, 2),
    }


def value_traps(
    price_to_book: Optional[float],
    retention: Optional[dict],
) -> list:
    """Почему дешевизна может оказаться не скидкой. Список признаков.

    Ни один из них не приговор компании и не опровержение расчёта. Каждый —
    вопрос, на который расчёт ответить не может, а читатель должен.

    **Глубокий дисконт к балансу.** P/B ниже половины при работающем деле
    означает, что рынок не верит либо в прибыль, либо в то, что она достанется
    владельцу. Формула такой случай видит дешёвым, потому что спрашивает
    только про размер денежного потока, а не про путь его к владельцу.

    **Удержанное не осело в капитале.** Прямое измерение того, что формула
    предполагает: она считает `g = ROE × (1 − payout)`, то есть уверена, что
    нерозданное становится капиталом. Тест Баффета проверяет это по факту.

    Признак остаётся содержательным и там, где рост взят нулевым по щедрой
    выплате: у Лукойла из 1 364 ₽ удержанного капитал не вырос, а упал на
    352 ₽. Формулу это не порочит — рост у неё и так ноль, — но про дело
    говорит: за семь лет заработанное сверх дивиденда владельцу в балансе не
    осталось.
    """
    found = []

    if price_to_book is not None and 0 < float(price_to_book) < TRAP_PRICE_TO_BOOK:
        found.append({
            "kind": "deep_discount",
            "value": round(float(price_to_book), 2),
            "reason": (
                f"P/B {float(price_to_book):.2f} — рынок платит меньше половины "
                f"балансового капитала. Это не всегда ошибка рынка: столько "
                f"стоит капитал, до которого владелец не дотягивается"
            ),
        })

    if retention and retention.get("share") is not None:
        share = float(retention["share"])
        if share < TRAP_RETENTION_SHARE:
            found.append({
                "kind": "retention_leak",
                "value": round(share, 2),
                "reason": (
                    f"из {retention['retained_per_share']:.0f} ₽ удержанной "
                    f"прибыли на акцию в капитал осело "
                    f"{retention['book_growth_per_share']:.0f} ₽ — "
                    f"{share:.0%}. Нерозданное до капитала владельца не "
                    f"дошло — осталось выяснить, куда"
                ),
            })

    return found


def assess_safety(
    price: Optional[float],
    reference: Optional[float],
    normal_earnings_per_share: Optional[float],
    risk_free_rate: Optional[float],
    screen_clears: Optional[bool] = None,
    book_value_per_share: Optional[float] = None,
    band_high: Optional[float] = None,
    price_to_book: Optional[float] = None,
    retention: Optional[dict] = None,
    ncav: Optional[dict] = None,
    leverage: Optional[float] = None,
    coverage_verdict: Optional[str] = None,
    structure_coverage: Optional[float] = None,
) -> Safety:
    """Собирает сигнал из трёх источников.

    `reference` — опорная оценка: лестница прибыли при множителе с надбавкой
    за риск, см. модульную строку документации. `normal_earnings_per_share` — нормальная прибыль по
    лестнице прибыли, из неё считается отдача, сопоставимая с купоном.

    Порядок проверок — от жёсткого к мягкому, и он не случаен. Сначала
    рубильник свода, потом ставка, потом стоимость. Ставка идёт раньше
    стоимости потому, что она не зависит от наших допущений о росте: отдача
    считается делением, а полоса — формулой с четырьмя входами, и когда они
    расходятся, верить надо той, где меньше наших решений.
    """
    safety = Safety(price=price, reference=reference, risk_free_rate=risk_free_rate)

    if not price or price <= 0:
        safety.reason = "нет цены"
        return safety

    safety.screen_clears = screen_clears

    # ── Запас по ставке ────────────────────────────────────────────────────
    if normal_earnings_per_share and normal_earnings_per_share > 0:
        safety.earnings_yield = round(normal_earnings_per_share / price * 100, 2)
        if risk_free_rate is not None:
            safety.yield_spread = round(
                safety.earnings_yield - float(risk_free_rate), 2
            )

    # ── Запас по стоимости ─────────────────────────────────────────────────
    if reference and reference > 0:
        safety.value_margin = round((reference - price) / reference, 3)

    safety.traps = value_traps(price_to_book, retention)
    safety.leverage = leverage
    safety.replacement = replacement_check(band_high or reference,
                                           book_value_per_share)
    if safety.replacement and safety.replacement.get("reason"):
        safety.notes.append(safety.replacement["reason"])

    # ── Опасность ──────────────────────────────────────────────────────────
    # Старше всех прочих состояний, потому что говорит не о цене, а о самой
    # компании. Стоит до любого из ранних возвратов: и «облигация выгоднее», и
    # «дорого» — суждения о цене, а цена не бывает настолько хороша или плоха,
    # чтобы способность баланса стереть владельца перестала иметь значение.
    #
    # Величины при этом уже посчитаны и остаются на виду. Мы меняем приговор,
    # а не прячем числа: читатель должен видеть и «запас 50%», и почему этот
    # запас ему не принадлежит.
    # **Обвиняет только то, что известно.** Рычаг сам по себе предупреждением
    # не делает: у X5 долг больше капитала вчетверо, но это аренда по МСФО 16,
    # а покрытие процентов у нас не посчитано — `finance_costs` заполнен у
    # пятнадцати компаний из сорока пяти. Пометить такую компанию опасной
    # значит наказать её за нашу неполноту, и это то самое правило, которое
    # соблюдается в ограждениях: отсутствие данных не равно плохим данным.
    #
    # Поэтому нужны обе половины: и величина долга, и доказанная тяжесть его
    # обслуживания.
    coverage = None if structure_coverage is None else float(structure_coverage)
    strained = coverage_verdict in ("strained", "refuse")

    danger = None
    if coverage_verdict == "refuse":
        danger = (
            "проценты платятся при операционном убытке — долг обслуживается "
            "не из заработка"
        )
    elif coverage is not None and coverage < COVERAGE_CRITICAL:
        danger = (
            f"проценты покрыты всего {coverage:.2f}× — они съедают две трети "
            f"операционной прибыли, и один слабый год выводит в убыток"
        )
    elif (
        strained and leverage is not None and leverage > LEVERAGE_DANGEROUS
    ):
        danger = (
            f"долг больше собственного капитала в {leverage:.0f} раз, и "
            f"проценты покрыты лишь {coverage:.2f}× — владельцу достаётся то, "
            f"что останется после кредитора"
        )

    # Большой рычаг при неизвестном покрытии — не приговор, но и не молчание:
    # запас объявлять нельзя, а причину надо назвать вслух, включая то, что
    # причина отчасти в нас.
    if (
        danger is None
        and leverage is not None
        and leverage > LEVERAGE_DANGEROUS
        and coverage is None
    ):
        if safety.signal in (FAVOURABLE, ACCEPTABLE):
            safety.signal = FAIR
        safety.notes.append(
            f"долг больше капитала в {leverage:.1f} раза, а покрытие процентов "
            f"не посчитано — финансовые расходы в отчёте не заполнены. "
            f"Утверждать, что компания его тянет, нечем"
        )

    if danger:
        safety.signal = DANGEROUS
        safety.reason = danger
        safety.notes.extend(trap["reason"] for trap in safety.traps)
        return safety

    # ── Сигнал ─────────────────────────────────────────────────────────────
    if safety.value_margin is None and safety.yield_spread is None:
        safety.reason = "не из чего считать: нет ни полосы, ни нормальной прибыли"
        return safety

    # Облигация выгоднее — состояние, перекрывающее всё остальное. Какой бы
    # ни была полоса, платить за неопределённость меньше, чем за купон, не
    # имеет смысла: это ровно тот случай, ради которого гл. 20 и написана.
    if safety.yield_spread is not None and safety.yield_spread < YIELD_SPREAD_THIN:
        safety.signal = BOND_BETTER
        safety.reason = (
            f"отдача {safety.earnings_yield:.1f}% ниже безрисковых "
            f"{float(risk_free_rate):.1f}% — облигация даёт больше и без "
            f"неопределённости"
        )
        return safety

    # Без опорной оценки сигнала не бывает. Раньше здесь стоял `FAIR`, и это
    # была прямая ложь: шесть компаний из сорока пяти — включая ту, которой
    # оценка отказана за операционный убыток, — получали подпись «около
    # стоимости», не имея никакой посчитанной стоимости вовсе. Один запас по
    # ставке приговором быть не может: отдача считается от нормальной прибыли,
    # а если полоса не сошлась, то и прибыли этой доверять нечему.
    if safety.value_margin is None:
        safety.signal = NO_SIGNAL
        safety.reason = (
            "стоимость не посчитана — одной отдачи для приговора мало: "
            "она считается от той же нормальной прибыли, из которой не "
            "сошлась полоса"
        )
        return safety

    if safety.value_margin < 0:
        safety.signal = EXPENSIVE
        safety.reason = (
            f"цена {price:.0f} ₽ выше опорной оценки {reference:.0f} ₽ "
            f"на {-safety.value_margin:.0%}"
        )
    elif safety.value_margin < MARGIN_ACCEPTABLE:
        safety.signal = FAIR
        safety.reason = (
            f"запас {safety.value_margin:.0%} — цена около стоимости, "
            f"ошибку в оценке такой запас не переживёт"
        )
    elif safety.value_margin < MARGIN_FAVOURABLE:
        safety.signal = ACCEPTABLE
        safety.reason = f"запас {safety.value_margin:.0%} — есть, но меньше трети"
    else:
        safety.signal = FAVOURABLE
        safety.reason = f"запас {safety.value_margin:.0%} от опорной оценки"

    # Тонкий запас по ставке понижает благоприятный сигнал до приемлемого:
    # полоса могла выйти щедрой из-за наших же допущений о росте, а отдача
    # таких допущений не содержит.
    if (safety.signal == FAVOURABLE and safety.yield_spread is not None
            and safety.yield_spread < YIELD_SPREAD_COMFORTABLE):
        safety.signal = ACCEPTABLE
        safety.notes.append(
            f"запас по ставке всего {safety.yield_spread:+.1f} п.п. — полоса "
            f"щедрее, чем отдача, и верить надо отдаче"
        )

    # Рычаг стоит перед тестом гл. 15 и после всего остального: он не меняет
    # посчитанных величин, он запрещает называть их запасом.
    #
    # Тест гл. 15 его перебивает намеренно. Там запас берётся не из будущего
    # заработка, а из оборотных активов за вычетом **всех** обязательств —
    # долг в этой величине уже вычтен, и второй раз наказывать за него значило
    # бы считать его дважды.
    if (
        leverage is not None
        and leverage > LEVERAGE_NO_SAFETY
        and safety.signal in (FAVOURABLE, ACCEPTABLE)
    ):
        safety.signal = FAIR
        safety.notes.append(
            f"долг больше капитала в {leverage:.1f} раза — запас по заработку "
            f"принадлежит кредитору прежде акционера, и называть его запасом "
            f"владельца нельзя"
        )

    # Тест гл. 15 поднимает сигнал, но **не до благоприятного**.
    #
    # Сперва он поднимал именно туда, и это было ошибкой прочтения. Глава 15 —
    # глава активного инвестора; защитному Грэм такие бумаги не предлагает
    # вовсе, а активному разрешает лишь набором из многих, потому что часть их
    # обязательно окажется мёртвой. Наш свод по умолчанию защитный, и зелёный
    # свет под ним означал бы не то, что написано в книге.
    #
    # Поэтому здесь «приемлемая» и строка о том, чей это случай. А при
    # признаках ловушки не поднимается и до неё: Башнефть с P/B 0,24 и утечкой
    # удержанного проходит гл. 15 арифметически, но разумному консервативному
    # инвестору предлагать её нельзя — можно только показать, что случай такой
    # бывает, и назвать его своим именем.
    if ncav:
        safety.ncav = ncav
    if ncav and ncav.get("passes") and safety.signal not in (FAVOURABLE, ACCEPTABLE):
        severe = any(
            trap["kind"] == "deep_discount"
            and trap["value"] < TRAP_PRICE_TO_BOOK_SEVERE
            for trap in safety.traps
        )
        safety.notes.append(
            "случай главы 15: цена ниже двух третей чистой стоимости "
            "оборотных активов. Это глава активного инвестора — защитному "
            "Грэм такие бумаги не предлагает, а активному только набором"
        )
        if not severe:
            safety.signal = ACCEPTABLE
            safety.reason = ncav["note"]



    # Признаки ловушки понижают благоприятный сигнал и всегда едут строкой.
    # Понижают, а не гасят: дисконт бывает и настоящей скидкой, и решить это
    # расчётом нельзя — можно только не дать назвать его благоприятным молча.
    if safety.traps:
        severe = any(
            trap["kind"] == "deep_discount"
            and trap["value"] < TRAP_PRICE_TO_BOOK_SEVERE
            for trap in safety.traps
        )
        if severe and safety.signal in (FAVOURABLE, ACCEPTABLE):
            # Не на ступень, а до потолка: при дисконте в три четверти и
            # больше понижение на одну ступень оставляло сигнал «приемлемая»,
            # то есть предложение покупать.
            safety.signal = FAIR
        elif safety.signal == FAVOURABLE:
            safety.signal = ACCEPTABLE
        safety.notes.extend(trap["reason"] for trap in safety.traps)

    # Непройденный свод понижает так же: дёшево — не то же самое, что хорошо.
    if safety.signal == FAVOURABLE and screen_clears is False:
        safety.signal = ACCEPTABLE
        safety.notes.append(
            "свод защитного инвестора не пройден — цена хороша, но отбор "
            "гл. 14 компания не проходит, и запас надёжности прикладывается "
            "к тому, что уже прошло отбор"
        )
    elif screen_clears is False:
        safety.notes.append("свод защитного инвестора не пройден")

    return safety
