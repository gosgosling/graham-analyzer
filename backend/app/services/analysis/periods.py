"""Длина отчётного периода — общее место для расчётов «поток к балансу».

Промежуточный отчёт публикуется нарастающим итогом: за полугодие в нём
примерно половина годовой прибыли, а баланс — полный, на отчётную дату.
Отношение одного к другому без приведения к году занижает показатель ровно
во столько раз, во сколько период короче года: полугодовой ROA выглядит вдвое
хуже годового, стоимость риска — вдвое лучше. Поэтому потоковые числители
умножаются на 12 / длину периода.

Отношения «поток к потоку» (Cost-to-Income) приводить к году не нужно —
множитель сокращается. Но только если числитель и знаменатель взяты за один
период: смешать LTM-выручку с полугодовыми расходами нельзя.
"""
from typing import Any

_MONTHS_BY_PERIOD = {"annual": 12, "semi_annual": 6}


def period_months(report: Any) -> int:
    """Сколько месяцев покрывает отчёт.

    Квартальные отчёты в проекте — накопительные с начала года, поэтому
    «Q3» означает девять месяцев, а не три. Неизвестный период считаем годом:
    так ведут себя заглушки в тестах и отчёты без проставленного типа, и
    молчаливое умножение на случайный множитель было бы хуже отсутствия
    приведения.
    """
    raw = getattr(report, "period_type", None)
    key = str(getattr(raw, "value", raw) or "").lower()

    if key in _MONTHS_BY_PERIOD:
        return _MONTHS_BY_PERIOD[key]

    if key == "quarterly":
        quarter = getattr(report, "fiscal_quarter", None)
        if isinstance(quarter, int) and 1 <= quarter <= 4:
            return quarter * 3

    return 12


def annualization_factor(report: Any) -> float:
    """Множитель, приводящий потоковую величину отчёта к годовой."""
    return 12 / period_months(report)


def is_full_year(report: Any) -> bool:
    """Покрывает ли отчёт полные двенадцать месяцев."""
    return period_months(report) == 12
