"""Округление величин «на акцию» — по масштабу, а не до двух знаков.

Два знака годятся для рублёвой бумаги и убивают копеечную. У ТГК-2 цена
0,0065 ₽ превращалась в `0.0`, у ТГК-1 при 0,0044 ₽ — тоже; вместе с ценой в
ноль уходили справедливая стоимость, опорная цена и число Грэма. График
получал ряд из нулей и рисовал прямую по нижнему краю, подписывая «0 ₽
сейчас» и «коридор 0 — 0,02 ₽».

В базе это уже лечили миграцией `penny_price_precision`, расширив колонки до
шести знаков. Точность терялась заново — на выходе из API.

Пороги те же, что у `formatPerShare` на фронте: иначе одно и то же число
покажется в таблице и на графике по-разному.
"""

from typing import Optional

__all__ = ("per_share", "decimals_for")


def decimals_for(value: float) -> int:
    """Сколько знаков оставить: чем дешевле бумага, тем больше их нужно."""
    size = abs(value)
    if size >= 1:
        return 2
    if size >= 0.01:
        return 4
    return 6


def per_share(value: Optional[float]) -> Optional[float]:
    """Округлить величину на акцию, сохранив значащие знаки."""
    if value is None:
        return None
    return round(float(value), decimals_for(float(value)))
