from app.utils.public_text import public_text


def test_пометки_ассистента_убираются_из_заметок():
    assert public_text("12.10.2026, Claude: перенесено вручную из форм МСФО") == \
        "12.10.2026: перенесено вручную из форм МСФО"
    assert public_text("Внесено Claude 12.10.2026, аналитиком не проверено.") == \
        "Внесено 12.10.2026, аналитиком не проверено."
    assert public_text("премия 5 п.п. и потолок роста 9,0% - предварительные суждения Claude, не пользователя.") == \
        "премия 5 п.п. и потолок роста 9,0% - предварительные суждения автора."


def test_без_имени_текст_не_меняется():
    text = "LLM_MODEL=anthropic/claude-3.5-haiku; перенесено по запросу пользователя"
    assert public_text(text) == text
